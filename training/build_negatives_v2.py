# DINUCLEOTIDE SHUFFLE (Pure Python)
# =============================================================================

def dinucleotide_shuffle(seq: str, rng: random.Random) -> str:
    """
    Dinucleotide shuffle preserving dinucleotide frequencies.
    Uses Altschul-Erickson algorithm: construct Eulerian path through
    dinucleotide graph.
    """
    seq = seq.upper()
    if len(seq) <= 2:
        return seq
    
    edges = defaultdict(list)
    for i in range(len(seq) - 1):
        edges[seq[i]].append(seq[i + 1])
    
    for node in edges:
        rng.shuffle(edges[node])
    
    path = [seq[0]]
    while edges[path[-1]]:
        next_nt = edges[path[-1]].pop()
        path.append(next_nt)
    
    return "".join(path)


