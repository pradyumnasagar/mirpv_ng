def compute_stats(records: List[SeqRecord], sample_fold: int = 100) -> Dict:
    """Compute distribution statistics for sequences."""
    if not records:
        return {"count": 0}
    
    rng = random.Random(42)
    seqs = [str(r.seq) for r in records]
    
    lengths = [len(s) for s in seqs]
    gcs = [compute_gc(s) for s in seqs]
    
    # Sample for folding
    fold_sample = rng.sample(seqs, min(sample_fold, len(seqs)))
    mfes = []
    pairs = []
    for seq in fold_sample:
        struct, mfe = run_rnafold(seq)
        if struct:
            mfes.append(mfe)
            pairs.append(struct.count("("))
    
    import numpy as np
    stats = {
        "count": len(records),
        "len_min": min(lengths),
        "len_max": max(lengths),
        "len_mean": np.mean(lengths),
        "len_std": np.std(lengths),
        "gc_mean": np.mean(gcs),
        "gc_std": np.std(gcs),
    }
    
    if mfes:
        stats["mfe_mean"] = np.mean(mfes)
        stats["mfe_std"] = np.std(mfes)
        stats["pairs_mean"] = np.mean(pairs)
        stats["pairs_std"] = np.std(pairs)
    
    return stats


