# BUCKET N3: STRUCTURED RNA DECOYS
# =============================================================================
#
# PURPOSE: Hard negatives that LOOK like miRNAs structurally but are NOT.
#
# CRITICAL PHILOSOPHY CHANGE:
#   - miRBase hairpins must NEVER be labeled negative
#   - miRBase may contain true miRNAs not yet in MirGeneDB
#   - Using miRBase as N3 causes systematic false negatives
#
# NEW SOURCE for N3: Confusable structured non-miRNA RNAs:
#   - tRNA (transfer RNA) - strong hairpin structure
#   - snoRNA (small nucleolar RNA) - often hairpin-like
#   - snRNA (small nuclear RNA) - structured elements
#   - rRNA (ribosomal RNA fragments) - stable structures
#
# These teach the model to discriminate based on miRNA-specific features
# (loop size, stem length, bulge patterns) rather than just "has hairpin".
#
# Provenance: N3|source=<type>|id=<id>|len=<len>
# =============================================================================

@dataclass
class BucketN3DecoyConfig:
    """Configuration for structured RNA decoy generation (new N3)."""
    decoys_fa: str          # Path to structured RNA FASTA
    positives_fa: str       # Path to MirGeneDB positives (for de-duplication)
    count: int = 500
    sources: Optional[List[str]] = None  # Filter by source type (None = all)
    min_len: int = 50       # Minimum sequence length
    max_len: int = 200      # Maximum sequence length
    seed: int = 42


def generate_bucket_n3_decoys(cfg: BucketN3DecoyConfig) -> List[SeqRecord]:
    """
    Generate N3 from structured RNA decoys (tRNA/snoRNA/snRNA/rRNA).
    
    FASTA format expected:
        >tRNA|Homo_sapiens|id=tRNA-Ala-AGC
        GGGGCTATAGCTCAG...
        
    Or any format where source type is parsed from ID.
    """
    print(f"[N3′] Loading structured RNA decoys from {cfg.decoys_fa}...")
    
    # Load positives for de-duplication
    positive_seqs = set()
    for rec in SeqIO.parse(cfg.positives_fa, "fasta"):
        positive_seqs.add(get_clean_seq(rec.seq))
    print(f"[N3′] Loaded {len(positive_seqs)} positive sequences for de-duplication")
    
    allowed_sources = cfg.sources if cfg.sources else ["tRNA", "snoRNA", "snRNA", "rRNA", "misc_RNA"]
    print(f"[N3′] Allowed source types: {allowed_sources}")
    
    candidates = []
    stats = {
        "total": 0,
        "rejected_len": 0,
        "rejected_dup": 0,
        "rejected_source": 0,
        "accepted": 0,
    }
    
    for rec in SeqIO.parse(cfg.decoys_fa, "fasta"):
        stats["total"] += 1
        seq = get_clean_seq(rec.seq)
        
        # Check length
        if len(seq) < cfg.min_len or len(seq) > cfg.max_len:
            stats["rejected_len"] += 1
            continue
        
        # Check duplication with positives
        if seq in positive_seqs:
            stats["rejected_dup"] += 1
            continue
        
        # Parse source type from ID (e.g., "tRNA|..." or "snoRNA...")
        rec_id = rec.id
        source_type = "unknown"
        for src in allowed_sources:
            if src.lower() in rec_id.lower():
                source_type = src
                break
        
        if source_type == "unknown" and cfg.sources:
            # If sources is specified, skip unknown types
            stats["rejected_source"] += 1
            continue
        
        candidates.append((rec, source_type))
        stats["accepted"] += 1
    
    print(f"[N3′] Total in decoy FASTA: {stats['total']}")
    print(f"[N3′] Rejected (length): {stats['rejected_len']}")
    print(f"[N3′] Rejected (duplicate): {stats['rejected_dup']}")
    print(f"[N3′] Rejected (source): {stats['rejected_source']}")
    print(f"[N3′] Accepted candidates: {stats['accepted']}")
    
    # Sample if needed
    rng = random.Random(cfg.seed)
    if len(candidates) > cfg.count:
        rng.shuffle(candidates)
        candidates = candidates[:cfg.count]
    
    records = []
    for rec, source_type in candidates:
        seq = get_clean_seq(rec.seq)
        new_rec = SeqRecord(
            Seq(seq_to_rna(seq)),
            id=f"N3|source={source_type}|id={rec.id}|len={len(seq)}",
            description="structured_rna_decoy"
        )
        records.append(new_rec)
    
    # Report source distribution
    source_counts = {}
    for rec, src in candidates:
        source_counts[src] = source_counts.get(src, 0) + 1
    print(f"[N3′] Source distribution: {source_counts}")
    print(f"[N3] Final count: {len(records)}")
    
    return records


# DEPRECATED: Old miRBase-based N3 generation
# =============================================================================
# WARNING: This function uses miRBase as negative source, which can mislabel
# true miRNAs. Use generate_bucket_n3_decoys() instead with --n3-decoys-fasta.
# =============================================================================

@dataclass
class BucketN3Config:
    mirbase_fa: str
    positives_fa: str
    species: str = "hsa"
    count: int = 500
    kmer_k: int = 6
    # STRICTER threshold per specification (was 0.6, now 0.4)
    jaccard_threshold: float = 0.4
    seed: int = 42


def generate_bucket_n3(cfg: BucketN3Config) -> List[SeqRecord]:
    """
    Extract miRBase decoy hairpins NOT matching MirGeneDB positives.
    
    Design rationale (publication-grade):
    - These are hairpin-structured sequences that LOOK like miRNAs
    - They teach the model to discriminate on subtle features
    - High-scoring N3s are EXPECTED (they are miRNA-like by design)
    - The k-mer filter (Jaccard < 0.4) ensures they're not near-duplicates
    
    Terminology: These are DECOYS, not true biological negatives.
    """
    print(f"[N3′] Loading MirGeneDB positives from {cfg.positives_fa}...")
    positives = list(SeqIO.parse(cfg.positives_fa, "fasta"))
    
    # Build k-mer index for similarity checking
    positive_seqs = []
    positive_kmers = []
    for rec in positives:
        seq = get_clean_seq(rec.seq)
        positive_seqs.append(seq)
        positive_kmers.append(get_kmers(seq, cfg.kmer_k))
    
    print(f"[N3′] Built k-mer index for {len(positives)} positives (k={cfg.kmer_k})")
    print(f"[N3′] Scanning miRBase {cfg.mirbase_fa} for {cfg.species} decoy candidates...")
    print(f"[N3′] Jaccard threshold: < {cfg.jaccard_threshold} (stricter = fewer false positives)")
    
    candidates = []  # Store (rec, max_jaccard) for provenance
    total_species = 0
    rejected_exact = 0
    rejected_similar = 0
    
    for rec in SeqIO.parse(cfg.mirbase_fa, "fasta"):
        if not rec.id.startswith(cfg.species):
            continue
        
        total_species += 1
        mb_seq = get_clean_seq(rec.seq)
        
        # Check 1: Exact/substring match - definitely exclude
        is_exact = any(pos in mb_seq or mb_seq in pos for pos in positive_seqs)
        if is_exact:
            rejected_exact += 1
            continue
        
        # Check 2: k-mer Jaccard similarity
        mb_kmers = get_kmers(mb_seq, cfg.kmer_k)
        max_jaccard = 0.0
        
        for pos_kmer_set in positive_kmers:
            inter = len(mb_kmers & pos_kmer_set)
            union = len(mb_kmers | pos_kmer_set)
            jaccard = inter / union if union > 0 else 0
            max_jaccard = max(max_jaccard, jaccard)
            
            # Early exit if definitely too similar
            if jaccard >= cfg.jaccard_threshold:
                break
        
        if max_jaccard >= cfg.jaccard_threshold:
            rejected_similar += 1
            continue
        
        # Accepted as decoy candidate
        candidates.append((rec, max_jaccard))
    
    print(f"[N3′] Total {cfg.species} in miRBase: {total_species}")
    print(f"[N3′] Rejected (exact/substring): {rejected_exact}")
    print(f"[N3′] Rejected (Jaccard >= {cfg.jaccard_threshold}): {rejected_similar}")
    print(f"[N3′] Decoy candidates: {len(candidates)}")
    
    rng = random.Random(cfg.seed)
    if len(candidates) > cfg.count:
        rng.shuffle(candidates)
        candidates = candidates[:cfg.count]
    
    records = []
    for rec, max_jaccard in candidates:
        # Provenance: N3|source=mirbase|id=<id>|jaccard=<val>
        new_rec = SeqRecord(
            Seq(seq_to_rna(get_clean_seq(rec.seq))),
            id=f"N3|source=mirbase|id={rec.id}|jaccard={max_jaccard:.3f}",
            description="decoy_hairpin"
        )
        records.append(new_rec)
    
    print(f"[N3] Final count: {len(records)}")
    return records


