def get_default_threads() -> int:
    """Get default thread count respecting HPC environment variables."""
    import os
    # Check HPC env vars in order of precedence
    for var in ['SLURM_CPUS_PER_TASK', 'PBS_NP', 'NSLOTS', 'OMP_NUM_THREADS']:
        if var in os.environ:
            try:
                return int(os.environ[var])
            except ValueError:
                pass
    # Fall back to min(available_cpu, 8)
    try:
        import multiprocessing
        return min(multiprocessing.cpu_count(), 8)
    except:
        return 4


