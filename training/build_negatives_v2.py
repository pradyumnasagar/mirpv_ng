def get_clean_seq(seq) -> str:
    """Normalize sequence: uppercase, U->T for DNA comparison."""
    return str(seq).upper().replace("U", "T")


def seq_to_rna(seq: str) -> str:
    """Convert to RNA alphabet (T->U)."""
    return seq.upper().replace("T", "U")


def compute_gc(seq: str) -> float:
    """Compute GC fraction."""
    seq = seq.upper()
    gc = sum(1 for c in seq if c in "GC")
    return gc / max(len(seq), 1)


def get_kmers(seq: str, k: int = 6) -> Set[str]:
    """Extract k-mers from sequence."""
    seq = seq.upper()
    return {seq[i:i+k] for i in range(len(seq) - k + 1)}


def run_rnafold(seq: str) -> Tuple[str, float]:
    """Run RNAfold and return (dot-bracket structure, MFE)."""
    if HAS_PARALLEL:
        results = run_rnafold_batch([seq])
        return results[0] if results else ("", 0.0)
    
    # Fallback: subprocess per sequence
    seq_rna = seq.upper().replace("T", "U")
    try:
        p = subprocess.Popen(
            ["RNAfold", "--noPS"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        out, _ = p.communicate(seq_rna + "\n", timeout=30)
        lines = out.strip().splitlines()
        if len(lines) < 2:
            return "", 0.0
        struct_line = lines[1]
        struct = struct_line.split()[0]
        try:
            mfe_str = struct_line.split("(")[-1].strip(" )")
            mfe = float(mfe_str)
        except Exception:
            mfe = 0.0
        return struct, mfe
    except Exception:
        return "", 0.0


