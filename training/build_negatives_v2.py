def load_bed_intervals(
    bed_path: str, 
    strict: bool = False, 
    flank: int = 0
) -> Optional[Dict[str, 'IntervalTree']]:
    """
    Load BED intervals for region masking with optional flank expansion.
    
    Args:
        bed_path: Path to BED file
        strict: If True, raise error if intervaltree not available (production safety)
        flank: Expand each interval by ±flank bp (default 0, no expansion)
               Intervals are clamped to start >= 0
    
    Returns:
        Dict mapping chromosome names to IntervalTree objects, or None on failure
    """
    if not HAS_INTERVALTREE:
        if strict:
            raise RuntimeError(
                f"STRICT BED MASKING ERROR: --exclude-bed or --include-bed was provided "
                f"but 'intervaltree' package is not installed.\n"
                f"Install with: pip install intervaltree\n"
                f"BED file: {bed_path}"
            )
        print("[WARNING] intervaltree not installed, skipping BED mask")
        return None
    
    try:
        trees = {}
        interval_count = 0
        with open(bed_path) as f:
            for line in f:
                if not line.strip() or line.startswith("#"):
                    continue
                parts = line.rstrip("\n").split("\t")
                if len(parts) < 3:
                    continue
                chrom = parts[0]
                start, end = int(parts[1]), int(parts[2])
                
                # Apply flank expansion with clamping
                if flank > 0:
                    start = max(0, start - flank)  # Clamp to >= 0
                    end = end + flank  # No upper clamp (contig length unknown)
                
                if chrom not in trees:
                    trees[chrom] = IntervalTree()
                trees[chrom].addi(start, end)
                interval_count += 1
        
        if flank > 0 and interval_count > 0:
            print(f"[BED] Loaded {interval_count} intervals with ±{flank}bp flank expansion")
        
        return trees if trees else None
    except Exception as e:
        if strict:
            raise RuntimeError(f"STRICT BED MASKING ERROR: Failed to load BED file: {bed_path}\nError: {e}")
        print(f"[WARNING] Failed to load BED {bed_path}: {e}")
        return None


def overlaps_intervals(chrom: str, start: int, end: int, trees: Optional[Dict]) -> bool:
    """Check if region overlaps any interval in trees."""
    if trees is None:
        return False
    tree = trees.get(chrom)
    if tree is None:
        return False
    return bool(tree.overlap(start, end))


def within_intervals(chrom: str, start: int, end: int, trees: Optional[Dict]) -> bool:
    """Check if region is within include intervals."""
    if trees is None:
        return True  # No restriction
    tree = trees.get(chrom)
    if tree is None:
        return False
    return bool(tree.overlap(start, end))


# =============================================================================
# BUCKET N1′: STRUCTURE-PRESERVING SHUFFLES (Composition Controls)
# =============================================================================
# PURPOSE: Prevent shortcut learning on GC / composition.
# These are EASY negatives by design - do NOT over-structure them.
#
# Required constraints:
#   - Dinucleotide shuffle (preserves dinuc frequency)
#   - Exact length match (automatic)
#   - GC content within ±2%
#   - Reject any shuffle that IMPROVES structural stability
#     (MFE_shuffle must be >= MFE_original - delta, i.e., less stable or equal)
#
# Provenance: N1|orig=<id>|gc=<val>|mfe=<val>
# =============================================================================

@dataclass
class BucketN1Config:
    positives_fa: str
    count: int
    shuffles_per_seq: int = 5
    gc_tolerance: float = 0.02  # ±2%
    # Structure rejection thresholds (per specification)
    # Reject if: mfe_shuffle < mfe_orig - mfe_delta (improved by too much)
    # OR: paired_frac_shuffle > paired_frac_orig + pf_delta
    mfe_delta: float = 2.0  # kcal/mol
    pf_delta: float = 0.05  # paired fraction
    seed: int = 42


def compute_paired_frac(structure: str) -> float:
    """Compute paired fraction from dot-bracket structure."""
    if not structure:
        return 0.0
    pairs = structure.count("(")
    return (pairs * 2) / len(structure)


def generate_bucket_n1(cfg: BucketN1Config) -> List[SeqRecord]:
    """
    Generate structure-preserving dinucleotide-shuffled negatives.
    
    Design rationale (publication-grade):
    - N1 must remain EASY negatives to prevent conservative boundary drift
    - Shuffles that improve structure are rejected (they would become hard negatives)
    - GC matching ensures composition control without structure matching
    
    Rejection criteria:
    - MFE: reject if mfe_shuffle < mfe_orig - delta (shuffle is more stable)
    - Paired fraction: reject if pf_shuffle > pf_orig + delta (more pairing)
    """
    print(f"[N1′] Loading positives from {cfg.positives_fa}...")
    positives = list(SeqIO.parse(cfg.positives_fa, "fasta"))
    print(f"[N1′] Loaded {len(positives)} positive sequences")
    print(f"[N1′] Rejection thresholds: MFE delta={cfg.mfe_delta} kcal/mol, PF delta={cfg.pf_delta}")
    
    rng = random.Random(cfg.seed)
    positive_seqs = {get_clean_seq(r.seq) for r in positives}
    
    # Pre-compute original MFE and paired fraction for structure rejection
    print(f"[N1′] Pre-computing original structures for rejection checks...")
    orig_cache = {}
    for rec in positives:
        orig_seq = get_clean_seq(rec.seq)
        struct, mfe = run_rnafold(orig_seq)
        orig_cache[rec.id] = {
            "mfe": mfe,
            "struct": struct,
            "pf": compute_paired_frac(struct),
        }
    
    candidates = []
    seen_seqs = set(positive_seqs)
    
    stats = {
        "total_attempts": 0,
        "rejected_gc": 0,
        "rejected_mfe": 0,
        "rejected_pf": 0,
        "rejected_dup": 0,
        "accepted": 0,
    }
    
    for rec in positives:
        orig_seq = get_clean_seq(rec.seq)
        orig_gc = compute_gc(orig_seq)
        orig_data = orig_cache[rec.id]
        orig_mfe = orig_data["mfe"]
        orig_pf = orig_data["pf"]
        
        for i in range(cfg.shuffles_per_seq):
            stats["total_attempts"] += 1
            shuffled = dinucleotide_shuffle(orig_seq, rng)
            
            # Check 1: Duplicate
            if shuffled in seen_seqs:
                stats["rejected_dup"] += 1
                continue
            
            # Check 2: GC tolerance (±2%)
            shuffle_gc = compute_gc(shuffled)
            if abs(shuffle_gc - orig_gc) > cfg.gc_tolerance:
                stats["rejected_gc"] += 1
                continue
            
            # Check 3: Structure rejection
            shuffle_struct, shuffle_mfe = run_rnafold(shuffled)
            
            # Reject if MFE improved by more than delta (more stable = bad)
            if shuffle_mfe < orig_mfe - cfg.mfe_delta:
                stats["rejected_mfe"] += 1
                continue
            
            # Reject if paired fraction improved by more than delta
            shuffle_pf = compute_paired_frac(shuffle_struct)
            if shuffle_pf > orig_pf + cfg.pf_delta:
                stats["rejected_pf"] += 1
                continue
            
            # Accepted
            seen_seqs.add(shuffled)
            stats["accepted"] += 1
            candidates.append({
                "seq": shuffled,
                "orig_id": rec.id,
                "gc": shuffle_gc,
                "mfe": shuffle_mfe,
                "pf": shuffle_pf,
                "seed": cfg.seed,
            })
    
    print(f"[N1′] Shuffle stats: {stats}")
    print(f"[N1′] Generated {len(candidates)} valid shuffled candidates")
    
    if len(candidates) > cfg.count:
        rng.shuffle(candidates)
        candidates = candidates[:cfg.count]
    
    records = []
    for c in candidates:
        # Provenance: N1|orig=<id>|gc=<val>|mfe=<val>|seed=<seed>
        records.append(SeqRecord(
            Seq(seq_to_rna(c["seq"])),
            id=f"N1|orig={c['orig_id']}|gc={c['gc']:.3f}|mfe={c['mfe']:.1f}|seed={c['seed']}",
            description="structure_preserving_shuffle"
        ))
    
    print(f"[N1′] Final count: {len(records)}")
    return records


# =============================================================================
# BUCKET N2′: SCAN-MATCHED GENOMIC BACKGROUND (Critical)
# =============================================================================
# PURPOSE: Match scan-mode inference distribution EXACTLY.
# These negatives teach the model what genome-wide scanning looks like.
#
# Extraction MUST mirror scan mode exactly:
#   - Same window_len, step
#   - Same tier1_energy_filter
#   - Same find_hairpins() logic
#   - Streaming (no genome-wide materialization)
#
# Hard exclusions (configurable BED):
#   - MirGeneDB loci ±5kb (default flank)
#   - miRBase loci ±5kb
#   - RepeatMasker regions
#   - Segmental duplications
#
# Distribution matching (IMPORTANT):
#   ❌ DO NOT match N2 to positives
#   ✅ MATCH N2 to scan-generated candidate pool
#
# Provenance: N2|chr:start-end|mfe_nt=<val>
# =============================================================================

@dataclass
class BucketN2Config:
    genome_fa: Optional[str]
    exclude_bed: Optional[str]  # Exclude known miRNA loci (with flanks)
    include_bed: Optional[str]  # Restrict to intronic/intergenic regions
    count: int
    # Scanner parameters (must match HairpinClassifier defaults EXACTLY)
    window_len: int = 100
    step: int = 10
    # Tier1 config (must match scanner defaults EXACTLY)
    tier1_min_len: int = 40
    tier1_max_len: int = 120
    tier1_min_pairs: int = 18
    tier1_min_mfe: float = -15.0
    tier1_max_unpaired_frac: float = 0.8
    # Flank size for BED interval expansion (bp)
    # Applied in-memory when loading exclude/include BED files
    flank: int = 5000
    seed: int = 42
    # Parallelism
    parallel_cfg: Optional[ParallelConfig] = None


def scanner_window_generator(
    genome_fa: str,
    window_len: int,
    step: int,
    exclude_trees: Optional[Dict],
    include_trees: Optional[Dict],
    seed: int,
) -> Generator[Tuple[str, int, int, str], None, None]:
    """
    STREAMING generator that produces windows like HairpinClassifier.scan_long_sequence().
    
    Yields: (chrom, start, end, seq)
    
    Key: This mimics generate_windows() from classifier.py exactly.
    """
    rng = random.Random(seed)
    
    # Collect all chromosome records first (needed for random access)
    chroms = []
    for rec in SeqIO.parse(genome_fa, "fasta"):
        chroms.append((rec.id, str(rec.seq)))
    
    # Shuffle chromosomes for variety
    rng.shuffle(chroms)
    
    for chrom_id, chrom_seq in chroms:
        n = len(chrom_seq)
        if n < window_len:
            continue
        
        # Generate window start positions (randomized within chrom)
        starts = list(range(0, n - window_len + 1, step))
        rng.shuffle(starts)
        
        for start in starts:
            end = start + window_len
            
            # Check exclude mask
            if overlaps_intervals(chrom_id, start, end, exclude_trees):
                continue
            
            # Check include mask (if provided)
            if include_trees is not None:
                if not within_intervals(chrom_id, start, end, include_trees):
                    continue
            
            win_seq = chrom_seq[start:end].upper()
            
            # Skip if contains N
            if "N" in win_seq:
                continue
            
            yield (chrom_id, start, end, win_seq)


def _process_window_batch(
    batch: List[Tuple[str, int, int, str]],
    tier1_cfg: Optional[TierConfig],
) -> List[Tuple[str, str, int, int, str, str, float]]:
    """
    Process a batch of windows: fold and filter.
    
    Returns list of (chrom, seq_clean, start, end, hp_seq, struct, mfe) for valid hairpins.
    """
    if not batch:
        return []
    
    # Extract sequences for batch folding
    seqs_rna = [seq_to_rna(win_seq) for _, _, _, win_seq in batch]
    
    # Batch fold
    if HAS_PARALLEL:
        fold_results = run_rnafold_batch(seqs_rna)
    else:
        fold_results = [run_rnafold(s) for s in seqs_rna]
    
    results = []
    for i, (chrom, start, end, win_seq) in enumerate(batch):
        seq_rna = seqs_rna[i]
        struct, mfe = fold_results[i]
        
        if not struct:
            continue
        
        # Apply tier1 filter
        if HAS_SCANNER and tier1_cfg:
            if not tier1_energy_filter(seq_rna, struct, mfe, tier1_cfg):
                continue
        else:
            pairs = struct.count("(")
            unpaired_frac = struct.count(".") / len(struct) if struct else 1.0
            if (len(seq_rna) < 40 or len(seq_rna) > 120 or
                pairs < 18 or mfe > -15.0 or unpaired_frac > 0.8):
                continue
        
        # Find hairpins
        if HAS_SCANNER:
            hairpins = find_hairpins(seq_rna, struct)
            if not hairpins:
                continue
            hp = hairpins[0]
            hp_seq = seq_rna[hp.start:hp.end]
            hp_len = hp.end - hp.start
        else:
            hp_seq = seq_rna
            hp_len = len(seq_rna)
        
        if hp_len < 50 or hp_len > 120:
            continue
        
        seq_clean = get_clean_seq(win_seq)
        results.append((chrom, seq_clean, start, end, hp_seq, struct, mfe))
    
    return results


def _process_window_batch_wrapper(args) -> List[Tuple[str, str, int, int, str, str, float]]:
    """Wrapper for parallel execution that accepts a single tuple argument."""
    batch, tier1_cfg = args
    return _process_window_batch(batch, tier1_cfg)


def generate_bucket_n2(cfg: BucketN2Config) -> List[SeqRecord]:
    """
    Generate scanner-matched background negatives using streaming + parallelism.
    
    CRITICAL: Uses the SAME filtering logic as HairpinClassifier to match
    the distribution of candidates encountered during sequence-only scanning.
    
    When parallel_cfg.jobs > 1, batches windows and processes in parallel.
    Utilizes mirpv_ng.parallel.parallel_map_stream for true multicore throughput.
    """
    if not cfg.genome_fa or cfg.count == 0:
        print("[N2] Skipping (no genome FASTA provided or count=0)")
        return []
    
    print(f"[N2] Loading genome from {cfg.genome_fa} (streaming)...")
    
    pcfg = cfg.parallel_cfg or ParallelConfig() if HAS_PARALLEL else None
    if pcfg and pcfg.jobs > 1:
        print_parallel_info(pcfg, "[N2] ")
    
    # Load BED masks with STRICT mode (fail loudly) and flank expansion
    exclude_trees = None
    if cfg.exclude_bed:
        print(f"[N2] Loading exclude mask from {cfg.exclude_bed} (flank=±{cfg.flank}bp)...")
        exclude_trees = load_bed_intervals(cfg.exclude_bed, strict=True, flank=cfg.flank)
        if exclude_trees:
            interval_count = sum(len(t) for t in exclude_trees.values())
            print(f"[N2] Loaded {interval_count} exclude intervals")
    
    include_trees = None
    if cfg.include_bed:
        print(f"[N2] Loading include mask from {cfg.include_bed}...")
        include_trees = load_bed_intervals(cfg.include_bed, strict=True)
        if include_trees:
            interval_count = sum(len(t) for t in include_trees.values())
            print(f"[N2] Loaded {interval_count} include intervals")
    
    # Create tier1 config (matches scanner defaults)
    tier1_cfg = TierConfig(
        min_len=cfg.tier1_min_len,
        max_len=cfg.tier1_max_len,
        min_pairs=cfg.tier1_min_pairs,
        min_mfe=cfg.tier1_min_mfe,
        max_unpaired_frac=cfg.tier1_max_unpaired_frac,
    ) if HAS_SCANNER else None
    
    records = []
    seen_seqs = set()
    windows_generated = 0
    windows_processed = 0
    
    print(f"[N2] Streaming windows (window_len={cfg.window_len}, step={cfg.step})...")
    
    # Generator for windows
    window_gen = scanner_window_generator(
        cfg.genome_fa, cfg.window_len, cfg.step,
        exclude_trees, include_trees, cfg.seed
    )
    
    if HAS_PARALLEL and pcfg and pcfg.jobs > 1:
        # Import here to avoid circularity if safe
        from mirpv_ng.parallel import parallel_map_stream, get_executor
        
        # We need a processor that takes a list of windows and returns results
        # parallel_map_stream passes chunks (lists of items) to the processor
        
        def batch_processor(batch: List[Tuple[str, int, int, str]]) -> List[Tuple[str, str, int, int, str, str, float]]:
            return _process_window_batch(batch, tier1_cfg)
            
        # Use parallel_map_stream
        # We need to manually handle 'seen_seqs' and count limits on the result stream
        with get_executor(pcfg) as executor:
            # We don't use 'parallel_map_stream' directly because it expects 'producer' to be the iterator
            # We can use executor.map_batches if we manually chunk, but parallel_map_stream does that.
            # wait, parallel_map_stream takes (cfg, producer, processor).
            # producer is window_gen. processor is batch_processor.
            
            result_stream = parallel_map_stream(
                pcfg,
                window_gen,
                batch_processor
            )
            
            for chrom, seq_clean, start, end, hp_seq, struct, mfe in result_stream:
                windows_processed += 1
                if len(records) >= cfg.count:
                    break
                if seq_clean in seen_seqs:
                    continue
                seen_seqs.add(seq_clean)
                
                # Provenance: N2|chr:start-end|mfe_nt=<val>
                hp_len = len(hp_seq)
                mfe_nt = mfe / hp_len if hp_len > 0 else 0.0
                rec_id = f"N2|{chrom}:{start}-{end}|mfe_nt={mfe_nt:.3f}"
                records.append(SeqRecord(
                    Seq(hp_seq),
                    id=rec_id,
                    description="scan_matched_genomic"
                ))
                
                if len(records) % 200 == 0:
                    print(f"[N2′] Progress: {len(records)}/{cfg.count} collected")

    else:
        # Sequential fallback (or parallel module missing)
        batch_size = 50
        current_batch = []
        
        for chrom, start, end, win_seq in window_gen:
            if len(records) >= cfg.count:
                break
            
            seq_clean = get_clean_seq(win_seq)
            if seq_clean in seen_seqs:
                continue
            
            current_batch.append((chrom, start, end, win_seq))
            windows_generated += 1
            
            if len(current_batch) >= batch_size:
                batch_results = _process_window_batch(current_batch, tier1_cfg)
                
                for chrom, seq_clean, start, end, hp_seq, struct, mfe in batch_results:
                    windows_processed += 1
                    if len(records) >= cfg.count:
                        break
                    
                    if seq_clean in seen_seqs:
                        continue
                    seen_seqs.add(seq_clean)
                    
                    hp_len = len(hp_seq)
                    mfe_nt = mfe / hp_len if hp_len > 0 else 0.0
                    rec_id = f"N2|{chrom}:{start}-{end}|mfe_nt={mfe_nt:.3f}"
                    records.append(SeqRecord(
                        Seq(hp_seq),
                        id=rec_id,
                        description="scan_matched_genomic"
                    ))
                
                current_batch = []
                if len(records) % 200 == 0:
                    print(f"[N2] Progress: {len(records)}/{cfg.count}")
        
        # Process remaining
        if current_batch and len(records) < cfg.count:
            batch_results = _process_window_batch(current_batch, tier1_cfg)
            for chrom, seq_clean, start, end, hp_seq, struct, mfe in batch_results:
                if len(records) >= cfg.count: break
                if seq_clean in seen_seqs: continue
                seen_seqs.add(seq_clean)
                hp_len = len(hp_seq)
                mfe_nt = mfe / hp_len if hp_len > 0 else 0.0
                rec_id = f"N2|{chrom}:{start}-{end}|mfe_nt={mfe_nt:.3f}"
                records.append(SeqRecord(Seq(hp_seq), id=rec_id, description="scan_matched_genomic"))

    print(f"[N2′] Processed/Verified {windows_processed} valid hairpins")
    if cfg.exclude_bed or cfg.include_bed:
        print(f"[N2′] BED masking active")
